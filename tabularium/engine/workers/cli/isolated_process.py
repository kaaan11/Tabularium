"""CLI transport adapters using the same bubblewrap runner as isolated tests.

Only the two built-in CLI adapters use these transports. Arbitrary in-process
WorkerAdapters cannot be contained by replacing their cwd or an attribute.
"""
from __future__ import annotations

import os
import threading
import time
from dataclasses import dataclass

from tabularium.engine.code_gate.isolated_run import SandboxError, run_isolated
from .bounded_process import Capture
from .transport import ProcessResult, worker_env_passthrough

WORKER_SANDBOX_UNAVAILABLE = "WORKER_SANDBOX_UNAVAILABLE"


@dataclass
class WorkerIsolation:
    hidden: tuple[str, ...]
    error: SandboxError | None = None

    def run(self, argv, cwd, timeout_s, output_limit, cancel, *, stdin_text=None, controls=None):
        names, _ = worker_env_passthrough()
        env = {name: os.environ[name] for name in names}
        # These values are generated by our OpenCode adapter, not inherited.
        env.update({name: value for name, value in (controls or {}).items()
                    if name in {"OPENCODE_DISABLE_PROJECT_CONFIG", "OPENCODE_PERMISSION"}})
        try:
            return run_isolated(cwd, list(argv), hidden=self.hidden, timeout=timeout_s,
                                output_limit=output_limit, worker_env=env,
                                stdin_text=stdin_text, cancel_event=cancel)
        except (SandboxError, OSError, ValueError) as exc:
            self.error = SandboxError(WORKER_SANDBOX_UNAVAILABLE,
                                      exc.detail if isinstance(exc, SandboxError) else str(exc))
            raise self.error from exc


class IsolatedNativeProcess:
    def __init__(self, argv, cwd, stdin_text, timeout_s, *, isolation):
        self.argv, self.cwd, self.stdin_text = argv, cwd, stdin_text
        self.timeout_s, self.isolation = timeout_s, isolation
        self._cancel = threading.Event()

    def cancel(self):
        self._cancel.set()
        return True

    def run(self, on_line=None):
        started = time.monotonic()
        if self._cancel.is_set():
            return ProcessResult("CANCELLED", None, (), (), 0)
        result = self.isolation.run(self.argv, self.cwd, self.timeout_s, 1024 * 1024,
                                    self._cancel, stdin_text=self.stdin_text)
        out, err = tuple(result.stdout.splitlines()), tuple(result.stderr.splitlines())
        if on_line:
            for stream, lines in (("stdout", out), ("stderr", err)):
                for line in lines:
                    on_line(stream, line)
        outcome = ("CANCELLED" if self._cancel.is_set() else
                   "TIMED_OUT" if result.timed_out else
                   "OUTPUT_LIMIT" if result.truncated else "EXITED")
        return ProcessResult(outcome, result.returncode if outcome == "EXITED" else None,
                             out, err, int((time.monotonic() - started) * 1000))


class IsolatedBoundedProcess:
    def __init__(self, argv, cwd, timeout_s, max_output_bytes, env=None, *, isolation):
        self.argv, self.cwd, self.env = argv, cwd, env
        self.timeout_s, self.max_output_bytes = timeout_s, max_output_bytes
        self.isolation = isolation
        self._cancel = threading.Event()

    def cancel(self):
        self._cancel.set()
        return True

    def run(self):
        if self._cancel.is_set():
            return Capture("CANCELLED", None)
        result = self.isolation.run(self.argv, self.cwd, self.timeout_s, self.max_output_bytes,
                                    self._cancel, controls=self.env)
        outcome = ("CANCELLED" if self._cancel.is_set() else
                   "TIMEOUT" if result.timed_out else
                   "OUTPUT_LIMIT" if result.truncated else "EXITED")
        return Capture(outcome, result.returncode, result.stdout,
                       bool(result.stderr), not result.truncated, result.stderr)
